"""Paired-release wheel benchmark: old strict IDs versus new forced_tokens.

Identical public grammar/vocabulary/state workloads; method selection happens
outside the timed region. Run each build in a fresh process, alternating order.
"""
from __future__ import annotations
import argparse,hashlib,json,statistics,sys,time
from pathlib import Path
parser=argparse.ArgumentParser()
parser.add_argument("--site",required=True,type=Path)
parser.add_argument("--output",required=True,type=Path)
parser.add_argument("--variant",required=True,choices=["baseline","candidate"])
parser.add_argument("--vocab-size",type=int,default=8192)
parser.add_argument("--repetitions",type=int,default=2000)
args=parser.parse_args()
assert args.vocab_size>=512 and args.repetitions>=20
if args.output.exists():raise SystemExit("Refusing to replace an existing benchmark receipt")
sys.path.insert(0,str(args.site))
import glrmask as g
import numpy as np
assert str(Path(g.__file__).resolve()).casefold().startswith(str(args.site.resolve()).casefold()),g.__file__

def summarize(values):
    values=sorted(values)
    def q(x):return values[min(len(values)-1,max(0,int(np.ceil(x*len(values)))-1))]
    return {"n":len(values),"p50_ns":q(.5),"p95_ns":q(.95),"p99_ns":q(.99),"p999_ns":q(.999),"max_ns":values[-1],"mean_ns":sum(values)/len(values)}

def reference(s):
    state=s.clone();out=[]
    for _ in range(10_000):
        if state.is_accepting():break
        ids=np.flatnonzero(state.mask())
        if len(ids)!=1:break
        id=int(ids[0]);out.append(id);state.commit_token(id)
    return out

def make_vocab(n):
    words={i:bytes([i]) for i in range(256)}
    for text in [b"ab",b"abc",b"abcdefgh",b"a"]:
        words[len(words)]=text
    while len(words)<n:
        words[len(words)]=f"word{len(words):07d}".encode()
    words[n+3]=b""
    return g.Vocab.from_id_to_bytes(words)

v=make_vocab(args.vocab_size)
rows=[]
for mode_name in ["FAST_BUILD","BALANCED","FAST_RUNTIME"]:
    mode=getattr(g.Optimization,mode_name)
    for name,source,prefix in [
        ("broad_identifier",'start root t W::=/[a-z0-9]+/ nt root::=W',[]),
        ("deterministic_bytes_aliases",'start root nt root::="abcdefghijklmnopqrstuvwxyz"',[]),
        ("two_singleton_chars",'start root nt root::="!?"',[]),
        ("long_singleton_chain",'start root nt root::="!!!!!!!!!!!!!!!!!!!!!!!!"',[]),
        ("accepting_prefix",'start root nt root::="a" "b"?', [97]),
        ("nested_inline",'grammar CHILD { start inner nt inner::="!?" } start root nt root::=CHILD "!"',[]),
        ("exact_event",None,[]),
    ]:
        desc=g.Grammar.exact(g.TokenSet([args.vocab_size+3])) if source is None else g.Grammar.from_glrm(source)
        c=desc.compile(v,optimization=mode)
        for cache in ["cold-state","mask-already-computed"]:
            state=c.start()
            for id in prefix:state.commit_token(id)
            if cache=="mask-already-computed":state.mask()
            method=state.forced_token_ids if args.variant=="baseline" else state.forced_tokens
            first_start=time.perf_counter_ns()
            first_result=method()
            first_query_ns=time.perf_counter_ns()-first_start
            # Oracle evaluation is intentionally AFTER the first timed query:
            # it may initialize shared grammar/vocabulary memoization.
            expected=reference(state)
            assert first_result==expected,(name,mode_name,first_result,expected)
            for _ in range(100):method()
            values=[]
            for _ in range(args.repetitions):
                start=time.perf_counter_ns();actual=method();elapsed=time.perf_counter_ns()-start
                assert actual==expected
                values.append(elapsed)
            rows.append({"case":name,"mode":mode_name,"cache":cache,"forced_ids":expected,"first_query_ns":first_query_ns,"forcing":summarize(values)})
            print(f"{name} {mode_name} {cache}: {statistics.median(values):.0f} ns ({len(expected)} forced IDs)",file=sys.stderr,flush=True)
output={"kind":"strict-forcing-paired-public-wheel-v1","variant":args.variant,"package":g.__file__,"vocab_size":args.vocab_size,"repetitions":args.repetitions,"rows":rows,"notes":["Timer measures public call only; construction/prefix commits/oracle validation excluded.","cold-state denotes no normal mask cache on the queried state; immutable compiled caches are warm.","Tests read-only query on unchanged state; no complete output masks are generated by this script inside timing.","Per-call Python timer overhead present in both variants; compare independent alternating fresh processes.","All returned ID sequences validated against public full-mask strict oracle.","first_query_ns is measured before the independent full-mask oracle can warm shared memoization."]}
args.output.parent.mkdir(parents=True,exist_ok=True)
args.output.write_text(json.dumps(output,indent=2),encoding="utf8")
print(json.dumps({"saved":str(args.output),"rows":len(rows),"variant":args.variant}))
