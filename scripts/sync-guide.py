#!/usr/bin/env python3
"""Generate Overview, package READMEs, full Guide and website shared content."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / 'docs/content'
REPO = 'https://github.com/IsaacBreen/glrmask'
RAW = 'https://raw.githubusercontent.com/IsaacBreen/glrmask/main/'
WEBSITE = 'https://glrmask.com'
PAPER = 'https://doi.org/10.5281/zenodo.23273556'
NOTICE = '<!-- Generated by scripts/sync-guide.py from docs/content. Do not edit this output. -->'
LICENSE = '## License\n\nLicensed under either the MIT License or the Apache License, Version 2.0, at your option.'
DATASETS = [('json', '2026-10-14', 'JSON Schema'), ('json-dynamic', '2026-10-14', 'JSON Schema Dynamic'), ('javascript', '2026-10-14', 'JavaScript')]


def read(name):
    return (CONTENT / (name + '.md')).read_text(encoding="utf-8").strip()


def links(flavor):
    items = [] if flavor == 'website' else [f'[Website]({WEBSITE})']
    if flavor != 'github':
        items.append(f'[GitHub]({REPO})')
    return ' · '.join(items + [f'[Paper]({PAPER})'])


def plot(dataset, measured, label, flavor):
    path = f'docs/assets/benchmark-tbm-{dataset}-{measured}'
    def asset(suffix):
        name = path + suffix
        # Keep GitHub's served JavaScript figure tied to its generated bytes.
        content = (ROOT / name).read_bytes() if dataset == 'javascript' else b''
        # Git's Windows checkout may use CRLF; GitHub serves canonical LF SVG text.
        if name.endswith('.svg'):
            content = content.replace(b'\r\n', b'\n')
        version = '?v=' + hashlib.sha256(content).hexdigest()[:12] if dataset == 'javascript' else ''
        return name + version
    alt = (f'{label} time between masks: measured GLRMask Static and llguidance 1.8.0 curves; '
           'logarithmic exceedance probability and latency axes. Lower is better.')
    if dataset=='json-dynamic':
        alt = ('JSON Schema time between masks: GLRMask faded, GLRMask dynamic prominent, and llguidance; '
               'logarithmic exceedance probability and latency axes. Lower is better.')
    if flavor == 'github':
        return (f'<p align="center">\n<picture>\n'
                f'  <source media="(prefers-color-scheme: dark)" srcset="{asset("-dark.svg")}">\n'
                f'  <img src="{asset(".svg")}" alt="{alt}" width="480">\n'
                '</picture>\n</p>')
    return f'<p><img src="{RAW}{asset(".png")}" alt="{alt}" width="480"></p>'


def benchmark_body(flavor):
    body = read('benchmarks')
    for dataset, measured, label in DATASETS:
        body = body.replace('{{' + dataset + '-plot}}', plot(dataset, measured, label, flavor))
    body = body.replace('{{dynamic}}', read('dynamic'))
    if flavor != 'github':
        body = re.sub(r'\]\((docs/[^)]+)\)', lambda m: f']({REPO}/blob/main/{m[1]})', body)
    return body


def install(language, heading):
    command = 'python -m pip install glrmask' if language == 'python' else 'cargo add glrmask'
    return f'{heading}\n\n```bash\n{command}\n```'


def quickstart(language, heading):
    return heading + '\n\n' + read(language + '-quickstart')


def getting_started(flavor):
    if flavor in ['python', 'rust']:
        return '\n\n'.join([install(flavor, '## Installation'), '## Usage\n\n' + read('usage'), quickstart(flavor, '## Quickstart')])
    return '\n\n'.join([
        '## Getting started', '### Installation',
        install('python', '#### Python'), install('rust', '#### Rust'),
        '### Usage\n\n' + read('usage'),
        quickstart('python', '### Python quickstart'), quickstart('rust', '### Rust quickstart'),
        read('usage-details'),
    ])


def document(flavor):
    if flavor in ['python', 'rust']:
        api = 'https://glrmask.com/api/python/' if flavor == 'python' else 'https://docs.rs/glrmask/latest/glrmask/'
        more = f'## Learn more\n\n[Full guide]({REPO}/blob/main/GUIDE.md) · [API reference]({api}) · [Benchmarks]({WEBSITE}/#benchmarks)'
        return '\n\n'.join(['# GLRMask', NOTICE, read('introduction'), links(flavor),
                              install(flavor, '## Installation'), quickstart(flavor, '## Quickstart'),
                              '## Core concepts\n\n' + read('usage'), more, LICENSE]) + '\n'
    return '\n\n'.join(['# GLRMask', NOTICE, read('introduction'), links(flavor),
                          '## Benchmarks\n\n' + benchmark_body(flavor), getting_started(flavor),
                          '## How it works\n\n' + read('how-it-works'), LICENSE]) + '\n'


def full_guide():
    reference = read('reference').replace('{{dynamic}}', read('dynamic'))
    return '\n\n'.join([
        NOTICE, read('introduction'), links('github'),
        '## Benchmarks\n\n' + benchmark_body('github'), '## Installation',
        install('python', '### Python'), install('rust', '### Rust'),
        '## Usage\n\n' + read('usage'),
        quickstart('python', '### Python quickstart'), quickstart('rust', '### Rust quickstart'),
        reference, '## How it works\n\n' + read('how-it-works'),
    ]) + '\n'


def website_payload():
    payload = {
        'schema': 'glrmask-shared-docs-v1',
        'overview_order': ['introduction', 'links', 'benchmarks', 'getting_started'],
        'introduction': read('introduction'), 'links': links('website'),
        'dynamic': read('dynamic'), 'usage': read('usage'),
        'installation': {'python': 'python -m pip install glrmask', 'rust': 'cargo add glrmask'},
        'quickstarts': {language: read(language + '-quickstart') for language in ['python', 'rust']},
        'usage_details': read('usage-details'), 'benchmark_markdown': read('benchmarks'),
        'chart': json.loads((CONTENT / 'tail-chart.json').read_text(encoding="utf-8")),
        'datasets': {'json': 'docs/benchmarks/json-schema-2026-10-14.json',
                     'javascript': 'docs/benchmarks/javascript-2026-10-14.json'},
    }
    payload['content_sha256'] = hashlib.sha256(json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    return json.dumps(payload, ensure_ascii=False, indent=2) + '\n'


def language_payload():
    # A narrow, benchmark-free import for both language references and the site.
    payload = {'schema': 'glrmask-language-docs-v1',
               'introduction': read('introduction'), 'usage': read('usage'),
               'installation': {'python': 'python -m pip install glrmask', 'rust': 'cargo add glrmask'},
               'quickstarts': {language: read(language + '-quickstart') for language in ['python', 'rust']},
               'guide_url': REPO + '/blob/main/GUIDE.md',
               'api_reference': {'python': WEBSITE + '/api/python/', 'rust': 'https://docs.rs/glrmask/latest/glrmask/'}}
    payload['content_sha256'] = hashlib.sha256(json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    return json.dumps(payload, ensure_ascii=False, indent=2) + '\n'


def rust_module_intro():
    source = (ROOT/'src/lib.rs').read_text()
    start = source.index('//!')
    end = source.index('//! # Typed bindings')
    prose = '\n\n'.join([NOTICE, read('introduction'), install('rust', '# Installation'),
                           quickstart('rust', '# Quickstart'), '# Core types\n\n' + read('usage'),
                           '# Learn more\n\n[Full guide](' + REPO + '/blob/main/GUIDE.md) · [API reference](https://docs.rs/glrmask/latest/glrmask/)'])
    block = '\n'.join('//! ' + line if line else '//!' for line in prose.splitlines()) + '\n//!\n'
    return source[:start] + block + source[end:]


def outputs():
    return {ROOT/'README.md': document('github'), ROOT/'README.rust.md': document('rust'),
            ROOT/'python/README.md': document('python'), ROOT/'python/PYTHON.md': document('python'), ROOT/'GUIDE.md': full_guide(),
            ROOT/'docs/website-content.json': website_payload(), ROOT/'docs/language-docs.json': language_payload(),
            ROOT/'src/lib.rs': rust_module_intro()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    cargo = tomllib.loads((ROOT/'Cargo.toml').read_text(encoding="utf-8"))
    python = tomllib.loads((ROOT/'python/pyproject.toml').read_text(encoding="utf-8"))
    assert cargo['package']['readme'] == 'README.rust.md', 'Cargo must select the Rust README'
    assert python['project']['readme'] == 'PYTHON.md', 'Python must select python/PYTHON.md'
    files = outputs()
    stale = [str(p.relative_to(ROOT)) for p, content in files.items() if not p.exists() or p.read_text(encoding="utf-8") != content]
    if args.check and stale:
        print('Stale documentation: ' + ', '.join(stale) + '; run python scripts/sync-guide.py', file=sys.stderr)
        return 1
    if not args.check:
        for path, content in files.items():
            path.write_text(content, encoding="utf-8")
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
