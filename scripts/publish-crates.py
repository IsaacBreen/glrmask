#!/usr/bin/env python3
"""Publish every unpublished GLRMask workspace crate to crates.io in dependency order.

Without --publish this only checks: it packages and verifies every publishable crate together
(so unpublished internal dependencies resolve locally), then fails if a version that is already
on crates.io has different sources here, which means a changed crate was not version-bumped.

With --publish it runs `cargo publish` for each crate version missing from crates.io, skipping
versions that already exist, so a rerun after a partial failure is safe.
"""
from __future__ import annotations

import argparse
import io
import json
import os
import subprocess
import sys
import tarfile
import time
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Workspace members that are built and shipped by other jobs, never published to crates.io.
NOT_ON_CRATES_IO = {"_glrmask"}
# Generated by cargo when packaging, so they differ between cargo versions.
GENERATED = {"Cargo.toml", "Cargo.lock", ".cargo_vcs_info.json"}
USER_AGENT = "GLRMask-release-workflow/1.0 (https://github.com/IsaacBreen/glrmask)"


def publishable_crates() -> list[dict]:
    """Return publishable workspace packages, each dependency before its dependents."""
    metadata = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--locked", "--no-deps", "--format-version", "1"], cwd=ROOT))
    packages = {
        p["name"]: p for p in metadata["packages"]
        if p["publish"] != [] and p["name"] not in NOT_ON_CRATES_IO
    }
    deps = {
        name: sorted({
            d["name"] for d in p["dependencies"]
            if d["name"] in packages and d["name"] != name
            and (d["kind"] != "dev" or d.get("req") not in (None, "*"))
        })
        for name, p in packages.items()
    }
    order: list[str] = []
    visiting: set[str] = set()

    def visit(name: str) -> None:
        if name in order:
            return
        if name in visiting:
            raise SystemExit(f"Dependency cycle through {name}")
        visiting.add(name)
        for dep in deps[name]:
            visit(dep)
        visiting.discard(name)
        order.append(name)

    for name in sorted(packages):
        visit(name)
    return [packages[name] for name in order]


def fetch(url: str) -> bytes | None:
    """GET url, returning None on 404 and retrying transient failures."""
    for attempt in range(5):
        try:
            request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
            with urllib.request.urlopen(request, timeout=60) as response:
                return response.read()
        except urllib.error.HTTPError as exc:
            if exc.code == 404:
                return None
            if exc.code < 500 and exc.code != 429:
                raise
            error: Exception = exc
        except (urllib.error.URLError, TimeoutError) as exc:
            error = exc
        time.sleep(2 ** attempt)
    raise RuntimeError(f"GET {url} failed: {error}")


def is_published(name: str, version: str) -> bool:
    return fetch(f"https://crates.io/api/v1/crates/{name}/{version}") is not None


def crate_files(data: bytes) -> dict[str, bytes]:
    """Map each source file in a .crate archive to its contents, without the top directory."""
    files = {}
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as archive:
        for member in archive.getmembers():
            if member.isfile():
                path = member.name.split("/", 1)[1]
                if path not in GENERATED:
                    files[path] = archive.extractfile(member).read()
    return files


def check(crates: list[dict], target_dir: Path) -> None:
    """Package and verify all crates together, then compare already-published versions."""
    command = ["cargo", "package", "--locked"]
    for crate in crates:
        command += ["-p", f"{crate['name']}@{crate['version']}"]
    subprocess.run(command, cwd=ROOT, check=True)

    stale = []
    for crate in crates:
        name, version = crate["name"], crate["version"]
        if not is_published(name, version):
            print(f"{name} {version}: new, will be published")
            continue
        published = fetch(f"https://static.crates.io/crates/{name}/{name}-{version}.crate")
        if published is None:
            raise RuntimeError(f"crates.io lists {name} {version} but has no download")
        local = crate_files((target_dir / "package" / f"{name}-{version}.crate").read_bytes())
        remote = crate_files(published)
        changed = sorted(p for p in local.keys() | remote.keys() if local.get(p) != remote.get(p))
        if changed:
            stale.append(f"{name} {version}: {', '.join(changed[:5])}"
                         + (f" and {len(changed) - 5} more" if len(changed) > 5 else ""))
        else:
            print(f"{name} {version}: already published, sources match")
    if stale:
        raise SystemExit(
            "These crates changed since their published version; bump their versions "
            "(and the requirements on them):\n  " + "\n  ".join(stale))


def publish(crates: list[dict]) -> None:
    if not os.environ.get("CARGO_REGISTRY_TOKEN"):
        raise SystemExit("CARGO_REGISTRY_TOKEN is required with --publish")
    for crate in crates:
        name, version = crate["name"], crate["version"]
        if is_published(name, version):
            print(f"{name} {version}: already on crates.io, skipped")
            continue
        print(f"{name} {version}: publishing", flush=True)
        # `check` already verified the build; cargo waits until the index has the new version,
        # so the next crate can depend on it.
        subprocess.run(["cargo", "publish", "--locked", "--no-verify", "-p", f"{name}@{version}"],
                       cwd=ROOT, check=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--publish", action="store_true",
                        help="publish missing versions (otherwise only package and check)")
    parser.add_argument("--github-output", action="store_true",
                        help="write pending=true|false to $GITHUB_OUTPUT after checking")
    args = parser.parse_args()

    crates = publishable_crates()
    print("Publish order: " + " -> ".join(f"{c['name']}@{c['version']}" for c in crates),
          flush=True)
    if args.publish:
        publish(crates)
        return

    target_dir = Path(json.loads(subprocess.check_output(
        ["cargo", "metadata", "--locked", "--no-deps", "--format-version", "1"],
        cwd=ROOT))["target_directory"])
    check(crates, target_dir)
    if args.github_output:
        pending = any(not is_published(c["name"], c["version"]) for c in crates)
        with open(os.environ["GITHUB_OUTPUT"], "a") as output:
            output.write(f"pending={str(pending).lower()}\n")


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as exc:
        sys.exit(exc.returncode)
