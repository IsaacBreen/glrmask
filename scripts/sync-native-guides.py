#!/usr/bin/env python3
"""Generate the native C++ and Node.js guides from shared and authored content.

Shared introduction and usage come from docs/content. Each language supplies its
own installation text, quickstart and details. Published 0.3 guides reuse the
shared introduction and the released usage recorded in python-api-releases.json.
"""
import argparse
import json
from pathlib import Path
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / 'docs' / 'content'
RELEASES = CONTENT / 'releases'
REPO = 'https://github.com/IsaacBreen/glrmask'
WEBSITE = 'https://glrmask.com'
PAPER = 'https://doi.org/10.5281/zenodo.23273556'
NOTICE = '<!-- Generated by scripts/sync-native-guides.py from docs/content. Do not edit this output. -->'
TAGS = {'0.3': 'v0.3.1'}
PACKAGE_VERSION = tomllib.loads((ROOT / 'Cargo.toml').read_text(encoding='utf-8'))['package']['version']
PACKAGE_MINOR = '.'.join(PACKAGE_VERSION.split('.')[:2])
NODE_VERSION = json.loads((ROOT / 'bindings' / 'node' / 'package.json').read_text(encoding='utf-8'))['version']

LANGUAGES = {
    'cpp': {
        'title': 'C++ and C',
        'api': f'{WEBSITE}/api/cpp/',
        'api_label': 'C++ API reference',
    },
    'javascript': {
        'title': 'JavaScript and TypeScript',
        'api': f'{WEBSITE}/api/javascript/',
        'api_label': 'JavaScript API reference',
    },
}


def read(name):
    return (CONTENT / (name + '.md')).read_text(encoding='utf-8').strip()


def read_release(release, name):
    return (RELEASES / release / (name + '.md')).read_text(encoding='utf-8').strip()


def links(language):
    return (f'[Website]({WEBSITE}) · [GitHub]({REPO}) · [Paper]({PAPER})')


def learn_more(language, release=None):
    ref = f'{REPO}/blob/{TAGS[release] if release else "main"}/GUIDE.md'
    return (f'## Learn more\n\n[Full guide]({ref}) · '
            f'[{LANGUAGES[language]["api_label"]}]({LANGUAGES[language]["api"]}) · '
            f'[Benchmarks]({WEBSITE}/#benchmarks)')


def usage(release=None):
    if release is None:
        return read('usage')
    data = json.loads((CONTENT / 'python-api-releases.json').read_text(encoding='utf-8'))
    return data[release]['usage'].strip()


def installation(language, release=None):
    if release is None:
        if language == 'cpp':
            return (f'Each [GitHub release]({REPO}/releases) includes static and shared libraries for '
                    'Windows x64 and arm64 (MSVC), macOS x64 and arm64 (macOS 11 or newer), and Linux x64 and '
                    'arm64 (glibc 2.28 or newer, or musl). Extract the archive for your platform, then:\n\n'
                    '```cmake\n'
                    f'find_package(glrmask {PACKAGE_MINOR} CONFIG REQUIRED)\n'
                    'target_link_libraries(application PRIVATE glrmask::glrmask)\n'
                    '```\n\n'
                    'Configure with `-DCMAKE_PREFIX_PATH=/absolute/path/to/glrmask`. C consumers link '
                    '`glrmask::c` and include `glrmask.h`. C++ consumers need C++17 and CMake 3.20 or '
                    'newer. To build from source instead, see [Building from source](#building-from-source).')
        return ('`@glrmask/node` runs the GLRMask engine as a Node.js addon. It needs Node.js 22 or '
                'newer, and includes prebuilt binaries for Windows x64 and arm64, macOS x64 and arm64, '
                'and Linux x64 and arm64 (glibc or musl).\n\n'
                '```sh\nnpm install @glrmask/node\n```\n\n'
                'The package provides CommonJS, ESM and TypeScript entry points.')
    if language == 'cpp':
        return (f'Version 0.3.1 provides static and shared CMake installations for Windows x64 (MSVC), '
                f'macOS x64 and arm64 (macOS 11 or newer), and Linux x64 and arm64 (glibc 2.35, built on '
                f'Ubuntu 22.04). Download the matching archive from the '
                f'[v0.3.1 release]({REPO}/releases/tag/v0.3.1) and extract it to an absolute prefix. '
                'C++ consumers need C++17 and CMake 3.20 or newer; a binary installation needs no Rust '
                'toolchain.\n\n'
                '```cmake\nfind_package(glrmask 0.3 CONFIG REQUIRED)\n'
                'target_link_libraries(application PRIVATE glrmask::glrmask)\n```\n\n'
                'Configure with `-DCMAKE_PREFIX_PATH=/absolute/path/glrmask-0.3.1`. '
                'Pure C consumers link `glrmask::c` and include `glrmask.h`.')
    return ('Use Node.js 22 or newer. The published 0.3.1 package includes native Node-API binaries '
            'for Windows x64, macOS x64 and arm64 (macOS 11 or newer), and Linux x64 and arm64 with '
            'glibc 2.35 or newer. A binary installation needs no Rust compiler, C++ compiler, or Python '
            'runtime.\n\n'
            '```sh\nnpm install @glrmask/node@0.3.1\n```\n\n'
            'The package provides CommonJS, ESM, and TypeScript entry points.')


def document(language, release=None):
    if release is None:
        quickstart = read(language + '-quickstart')
        details = read(language + '-details')
    else:
        quickstart = read_release(release, language + '-quickstart')
        details = read_release(release, language + '-details')
    title = LANGUAGES[language]['title']
    return '\n\n'.join([
        f'# {title}', NOTICE, read('introduction'), links(language),
        '## Installation\n\n' + installation(language, release),
        '## Usage\n\n' + usage(release),
        '## Quickstart\n\n' + quickstart,
        learn_more(language, release), details,
    ]) + '\n'


def outputs():
    files = {
        ROOT / 'bindings' / 'cpp' / 'README.md': document('cpp'),
        ROOT / 'bindings' / 'node' / 'README.md': document('javascript'),
    }
    for release in ['0.3']:
        for language in LANGUAGES:
            files[RELEASES / release / (language + '.md')] = document(language, release)
    return files


def validate(files):
    release_text = ''.join(content for path, content in files.items()
                           if 'releases' in path.parts)
    for forbidden in ['Module', 'Expr', 'MaskStrategy', 'BoundaryMaskStrategy']:
        assert forbidden not in release_text, f'Published 0.3 guide mentions source-only API: {forbidden}'
    assert 'PreparedGrammar' in release_text, 'Published 0.3 guide must document PreparedGrammar'
    assert 'Optimization' in release_text, 'Published 0.3 guide must document Optimization'
    for path, content in files.items():
        assert content.startswith('# '), f'Missing title: {path}'
        assert read('introduction') in content, f'Missing shared introduction: {path}'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = outputs()
    validate(files)
    stale = [str(path.relative_to(ROOT)) for path, content in files.items()
             if not path.exists() or path.read_text(encoding='utf-8') != content]
    if args.check and stale:
        print('Stale native documentation: ' + ', '.join(stale)
              + '; run python scripts/sync-native-guides.py', file=sys.stderr)
        return 1
    if not args.check:
        for path, content in files.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
